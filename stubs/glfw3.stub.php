{
    private function __construct() {}

    public function pointer(): int {}

    public static function fromPointer(int $pointer): static {}
}

/** A monitor GLFW reports: from glfwGetMonitors(), glfwGetPrimaryMonitor() or glfwGetWindowMonitor(). */
final class GLFWmonitor
{
    private function __construct() {}

    public function pointer(): int {}

    public static function fromPointer(int $pointer): static {}
}

/** GLFWvidmode: one mode a monitor can run. */
final class GLFWvidmode
{
    public int $width = 0;

    public int $height = 0;

    public int $redBits = 0;

    public int $greenBits = 0;

    public int $blueBits = 0;

    public int $refreshRate = 0;
}

/** GLFWgammaramp: one list of 16-bit values per channel, all the same length. */
final class GLFWgammaramp
{
    /** @var list<int> */
    public array $red = [];

    /** @var list<int> */
    public array $green = [];

    /** @var list<int> */
    public array $blue = [];

    public function __construct(array $red = [], array $green = [], array $blue = []) {}
}

/** GLFWimage: RGBA8 pixels, 4 × width × height bytes, rows top to bottom. */
final class GLFWimage
{
    public int $width = 0;

    public int $height = 0;

    public string $pixels = "";

    public function __construct(int $width = 0, int $height = 0, string $pixels = "") {}
}

